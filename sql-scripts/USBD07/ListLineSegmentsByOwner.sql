SELECT
    LS.SEGMENT_ID,
    LS.LENGTH_KM,
    LS.ELECTRIF_TYPE,
    LS.GAUGE_ID,
    LS.MAX_WEIGHT_KG_M,
    LS.SPEED_LIMIT_KMH,
    LS.TRACK_NUMBER,
    LS.POSITION,
    L.LINE_ID,
    L.NAME AS LINE_NAME
FROM
    LINE_SEGMENT LS
        JOIN LINE L ON LS.LINE_ID = L.LINE_ID
        JOIN COMPANY C ON L.OWNER_ID = C.COMPANY_ID
WHERE
    (:owner_id IS NULL OR C.COMPANY_ID = :owner_id)
ORDER BY
    L.LINE_ID,
    LS.POSITION;